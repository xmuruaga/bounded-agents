"""
Multi-run AgentDojo evaluation with statistical aggregation.

Runs the utility evaluation N times per suite and reports:
  - mean UPR per domain per condition
  - std, min, max, n
  - weighted aggregate across all suites

Usage:
  python evals/agentdojo/run_multirun.py --runs 3
  python evals/agentdojo/run_multirun.py --runs 5 --suite workspace
  python evals/agentdojo/run_multirun.py --runs 3 --all --output results/multirun/

Results are written to JSON and a LaTeX table fragment for direct inclusion
in the paper.
"""


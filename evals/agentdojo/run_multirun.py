def aggregate_runs(run_results: list[dict]) -> dict:
    """Compute mean, std, min, max over N runs for each condition × metric.

    run_results: list of dicts, each dict is {condition_name: {upr, asr, ...}}
    as returned by run_suite().
    """
    if not run_results:
        return {}

    conditions = [k for k in run_results[0].keys() if isinstance(run_results[0][k], dict)]
    aggregated = {}

    for condition in conditions:
        uprs = [r[condition]["upr"] for r in run_results if condition in r and "upr" in r[condition]]
        asrs = [r[condition]["asr"] for r in run_results if condition in r and "asr" in r[condition]]

        if not uprs:
            continue

        aggregated[condition] = {
            "upr_mean": statistics.mean(uprs),
            "upr_std": statistics.stdev(uprs) if len(uprs) > 1 else 0.0,
            "upr_min": min(uprs),
            "upr_max": max(uprs),
            "asr_mean": statistics.mean(asrs),
            "asr_std": statistics.stdev(asrs) if len(asrs) > 1 else 0.0,
            "asr_min": min(asrs),
            "asr_max": max(asrs),
            "n": len(uprs),
            "raw_uprs": uprs,
            "raw_asrs": asrs,
        }

    return aggregated


def format_upr(mean: float, std: float, n: int) -> str:
    """Format UPR as 'XX.X ± Y.Y%' for paper tables."""
    if n == 1:
        return f"{mean*100:.1f}\\%"
    return f"{mean*100:.1f} $\\pm$ {std*100:.1f}\\%"


def format_asr(mean: float, std: float, n: int) -> str:
    """Format ASR as '0.0%' or 'X.X ± Y.Y%'."""
    if mean == 0.0:
        return "\\textbf{0.0\\%}"
    if n == 1:
        return f"{mean*100:.1f}\\%"
    return f"{mean*100:.1f} $\\pm$ {std*100:.1f}\\%"


def generate_latex_table(suite_results: dict, n_runs: int) -> str:
    """Generate a LaTeX table fragment for the paper."""
    lines = [
        "% Auto-generated by run_multirun.py — do not edit manually",

        "\\begin{table}[H]",
        "\\centering",
        "\\footnotesize",
        f"\\caption{{Utility preservation and attack success rate across four AgentDojo suites.",
        f"  Mean $\\pm$ std over {n_runs} independent runs.",
        f"  APC evaluated in interactive mode (C4-only denials auto-approved).",
        f"  Progent column: \\textbf{{[TO BE FILLED — see comparison-protocol.md]}}.}}",
        "\\label{tab:utility-multirun}",
        "\\begin{tabular}{@{}lrrrrr@{}}",
        "\\toprule",
        "\\textbf{Suite} & \\textbf{Baseline UPR} & \\textbf{APC UPR} & "
        "\\textbf{Progent UPR} & \\textbf{APC ASR} & \\textbf{Progent ASR} \\\\",
        "\\midrule",
    ]

    total_runs_baseline = 0
    total_runs_apc = 0
    weighted_baseline_upr = 0.0
    weighted_apc_upr = 0.0

    suite_run_counts = {
        "workspace": 560, "banking": 144, "travel": 140, "slack": 105
    }

    for suite_name, agg in suite_results.items():
        n_task_runs = suite_run_counts.get(suite_name, "?")
        baseline = agg.get("baseline", {})
        # "apc-approved" = interactive mode (C4 auto-approved); matches paper's "interactive" column
        apc = agg.get("apc-approved", agg.get("apc-no-overrides", agg.get("apc-overrides", {})))

        baseline_upr_str = format_upr(
            baseline.get("upr_mean", 0),
            baseline.get("upr_std", 0),
            baseline.get("n", 1),
        )
        apc_upr_str = format_upr(
            apc.get("upr_mean", 0),
            apc.get("upr_std", 0),
            apc.get("n", 1),
        )
        apc_asr_str = format_asr(
            apc.get("asr_mean", 0),
            apc.get("asr_std", 0),
            apc.get("n", 1),
        )

        suite_label = suite_name.capitalize()
        lines.append(
            f"{suite_label} ({n_task_runs} runs/run) & "
            f"{baseline_upr_str} & "
            f"{apc_upr_str} & "
            f"[Progent] & "
            f"{apc_asr_str} & "
            f"[Progent] \\\\"
        )

        if isinstance(n_task_runs, int):
            total_runs_baseline += n_task_runs
            total_runs_apc += n_task_runs
            weighted_baseline_upr += baseline.get("upr_mean", 0) * n_task_runs
            weighted_apc_upr += apc.get("upr_mean", 0) * n_task_runs

    # Weighted aggregate row
    if total_runs_baseline > 0:
        wavg_baseline = weighted_baseline_upr / total_runs_baseline
        wavg_apc = weighted_apc_upr / total_runs_apc
        lines.append("\\midrule")
        lines.append(
            f"\\textbf{{Weighted avg.}} & "
            f"{wavg_baseline*100:.1f}\\% & "
            f"{wavg_apc*100:.1f}\\% & "
            f"[Progent] & --- & --- \\\\"
        )

    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]

    return "\n".join(lines)


def run_suite_n_times(suite_name: str, model_id: str, n: int,
                      output_dir: Path) -> tuple[list[dict], dict]:
    """Run a single suite N times and return raw results + aggregated stats.

    Each run starts with a fresh call to run_suite() which creates new
    pipeline elements, session state, and API clients. No state is shared
    between runs except the benchmark data itself (which is read-only).
    """
    print(f"\n{'='*60}")
    print(f"Suite: {suite_name} | Model: {model_id} | Runs: {n}")
    print(f"{'='*60}")
    print(f"Run isolation: each run creates fresh pipeline state.")
    print(f"Failed runs are excluded and noted; not retried.")

    raw_results = []
    failed_runs = []

    for i in range(n):
        print(f"\n--- Run {i+1}/{n} ---")
        try:
            # run_suite() creates fresh AgentDojo pipeline elements per call.
            # No shared in-memory state between calls.
            result = run_suite(suite_name, model_id)
            # Capture a deep copy of the result before run_suite() overwrites
            # its results directory on the next call.
            import copy
            run_data = copy.deepcopy(result)
            raw_results.append(run_data)

            # Write checkpoint immediately — recoverable if process dies mid-run
            checkpoint_path = output_dir / f"{suite_name}_run{i+1}_checkpoint.json"
            checkpoint = {
                condition: {k: v for k, v in vals.items() if k != "results"}
                for condition, vals in run_data.items()
                if isinstance(vals, dict)
            }
            with open(checkpoint_path, "w") as f:
                json.dump(checkpoint, f, indent=2)

            print(f"  Run {i+1} complete. Checkpoint: {checkpoint_path.name}")
            for condition, vals in run_data.items():
                if isinstance(vals, dict):
                    print(f"    {condition}: UPR={vals.get('upr', '?'):.4f}  ASR={vals.get('asr', '?'):.4f}")
        except Exception as e:
            failed_runs.append({"run": i+1, "error": str(e)})
            print(f"  Run {i+1} FAILED (excluded): {e}")

    if failed_runs:
        print(f"\nWARNING: {len(failed_runs)} run(s) failed and were excluded:")
        for f in failed_runs:
            print(f"  Run {f['run']}: {f['error']}")

    if not raw_results:
        print(f"  ERROR: all runs failed for {suite_name}")
        return [], {}

    agg = aggregate_runs(raw_results)
    print(f"\nAggregated ({len(raw_results)} successful runs, {len(failed_runs)} excluded):")
    for condition, stats in agg.items():
        print(f"  {condition}:")
        print(f"    UPR  mean={stats['upr_mean']*100:.1f}%  std={stats['upr_std']*100:.1f}%"
              f"  min={stats['upr_min']*100:.1f}%  max={stats['upr_max']*100:.1f}%  n={stats['n']}")
        print(f"    ASR  mean={stats['asr_mean']*100:.1f}%  std={stats['asr_std']*100:.1f}%"
              f"  min={stats['asr_min']*100:.1f}%  max={stats['asr_max']*100:.1f}%  n={stats['n']}")

    return raw_results, agg


def main():
    parser = argparse.ArgumentParser(
        description="Multi-run AgentDojo evaluation with statistical aggregation."
    )
    parser.add_argument("--runs", type=int, default=3,
                        help="Number of independent runs per suite (default: 3)")
    parser.add_argument("--suite", type=str, default=None,
                        help="Single suite to evaluate (default: workspace)")
    parser.add_argument("--all", action="store_true",
                        help="Evaluate all four suites")
    parser.add_argument("--model", type=str,
                        default="sonnet",
                        help="Model alias ('haiku', 'sonnet') or full Bedrock model ID. "
                             "Aliases resolve via suite_config.MODELS. "
                             "Default: sonnet (Claude Sonnet 4.6)")
    parser.add_argument("--output", type=str, default=None,
                        help="Output directory for results (default: results/multirun/TIMESTAMP/)")
    parser.add_argument("--dry-run", action="store_true",
                        help="Validate setup without making API calls. "
                             "Prints what would be run and exits.")
    args = parser.parse_args()

    # Resolve model alias → full Bedrock model ID
    from suite_config import MODELS
    model_id = MODELS.get(args.model, args.model)  # alias or pass-through full ID

    # Determine suites to run
    if args.all:
        suites = ALL_SUITES
    elif args.suite:
        suites = [args.suite]
    else:
        suites = ["workspace"]

    # Output directory
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    output_dir = Path(args.output) if args.output else \
        Path(__file__).parent / "results" / "multirun" / timestamp
    output_dir.mkdir(parents=True, exist_ok=True)

    print(f"\nMulti-run evaluation")
    print(f"Suites: {suites}")
    print(f"Runs per suite: {args.runs}")
    print(f"Model alias: {args.model!r}  →  {model_id}")
    print(f"Output: {output_dir}")

    # --- Dry-run: validate setup without API calls ---
    if args.dry_run:
        print(f"\n{'='*60}")
        print(f"DRY RUN — no API calls will be made")
        print(f"{'='*60}")
        # Validate imports and suite configs
        try:
            from suite_config import get_suite_config
            from apc_defense.pipeline_element import APCDefenseElement
            from apc_defense.action_classifier import ActionClassifier
            from apc_defense.scope_registry import ScopeRegistry
            print("✓  Imports OK")
        except ImportError as e:
            print(f"✗  Import error: {e}")
            return 1

        total_calls = 0
        for suite_name in suites:
            try:
                classifier, scope, max_tasks = get_suite_config(suite_name)
                from agentdojo.task_suite.load_suites import get_suite
                suite_obj = get_suite("v1.2.2", suite_name)
                n_tasks = min(max_tasks, len(suite_obj.user_tasks))
                n_inj = len(suite_obj.injection_tasks)
                calls_per_run = n_tasks * n_inj
                calls_total = calls_per_run * 3 * args.runs  # 3 conditions
                total_calls += calls_total
                cost_est = calls_total * 0.012  # Sonnet medium estimate
                print(f"✓  {suite_name}: {n_tasks} tasks × {n_inj} injections = "
                      f"{calls_per_run} pairs/run × 3 conditions × {args.runs} runs "
                      f"= {calls_total} calls (~${cost_est:.0f} at Sonnet medium est.)")
            except Exception as e:
                print(f"✗  {suite_name}: {e}")
                return 1

        total_cost_est = total_calls * 0.012
        print(f"\nTotal: {total_calls} calls (~${total_cost_est:.0f} at Sonnet medium est.)")
        print(f"\nDry run complete. Re-run without --dry-run to execute.")
        return 0

    # Record protocol metadata — capture environment precisely
    import subprocess
    import platform

    def get_git_commit() -> str:
        try:
            return subprocess.check_output(
                ["git", "rev-parse", "HEAD"], stderr=subprocess.DEVNULL
            ).decode().strip()
        except Exception:
            return "unknown"

    model_short = args.model if args.model in ("haiku", "sonnet") else "custom"
    protocol_meta = {
        "timestamp": timestamp,
        "model_alias": args.model,
        "model_id_resolved": model_id,
        "agentdojo_version": "v1.2.2",
        "runs_per_suite": args.runs,
        "suites": suites,
        "apc_mode": "interactive",
        "apc_git_commit": get_git_commit(),
        "protocol_doc": "evals/comparison-protocol.md",
        "python_version": platform.python_version(),
        "platform": platform.platform(),
        "aws_region": os.getenv("AWS_DEFAULT_REGION", "eu-central-1"),
        "prompt_caching": "disabled — verify ANTHROPIC_CACHE=0 was set",
        "temperature": "default (not overridden)",
        "top_p": "default (not overridden)",
        "max_tokens_per_turn": "default (not overridden)",
        "run_order": "sequential per suite",
        "failed_runs_excluded": True,
        "retry_policy": "no retries on API errors",
    }

    all_suite_results = {}
    all_raw = {}
    all_failed = {}

    for suite_name in suites:
        raw, agg = run_suite_n_times(suite_name, model_id, args.runs, output_dir)
        all_suite_results[suite_name] = agg
        all_raw[suite_name] = raw
        # failed_runs is local to run_suite_n_times; re-expose via agg metadata
        all_failed[suite_name] = {
            "successful_runs": len(raw),
            "requested_runs": args.runs,
            "excluded_runs": args.runs - len(raw),
        }

    # Write results — separate summary from per-run details to keep JSON manageable
    # Summary: aggregated stats only (small, suitable for paper verification)
    # Details: per-run raw results (large, one file per suite per run)
    summary_output = {
        "protocol": protocol_meta,
        "run_summary": all_failed,
        "aggregated": all_suite_results,
        # raw_uprs and raw_asrs are included in aggregated for traceability
    }

    summary_path = output_dir / "multirun_summary.json"
    with open(summary_path, "w") as f:
        json.dump(summary_output, f, indent=2)
    print(f"\nSummary written to: {summary_path}")

    # Per-run details: strip the large 'results' lists to keep files manageable
    # Full details are already saved by run_suite() in results/utility-{suite}-{model}/
    for suite_name, runs in all_raw.items():
        for i, run_data in enumerate(runs):
            run_summary = {
                condition: {k: v for k, v in vals.items() if k != "results"}
                for condition, vals in run_data.items()
                if isinstance(vals, dict)
            }
            run_path = output_dir / f"{suite_name}_run{i+1}.json"
            with open(run_path, "w") as f:
                json.dump(run_summary, f, indent=2)

    print(f"Per-run summaries written to: {output_dir}/{{suite}}_run{{N}}.json")

    # Generate LaTeX table fragment
    latex = generate_latex_table(all_suite_results, args.runs)
    latex_path = output_dir / "table_utility_multirun.tex"
    with open(latex_path, "w") as f:
        f.write(latex)
    print(f"LaTeX table written to: {latex_path}")
    print("\nLaTeX table preview:")
    print(latex)

    return 0


if __name__ == "__main__":
    sys.exit(main())
